export function getLevelsForAgeGroup(ageGroup: AgeGroupId): LevelConfig[] {
  return LEVELS.map((lvl) => {
    if (ageGroup === 'under_5') {
      return {
        ...lvl,
        targetChickens: Math.max(3, Math.round(lvl.targetChickens * 0.45)),
        waveSize: Math.max(2, Math.round(lvl.waveSize * 0.6)),
        speedMultiplier: Math.max(0.40, Number((lvl.speedMultiplier * 0.55).toFixed(2))),
        eggDropRate: Math.max(0.0008, Number((lvl.eggDropRate * 0.35).toFixed(4))),
      };
    }
    if (ageGroup === '10_plus') {
      return {
        ...lvl,
        targetChickens: Math.round(lvl.targetChickens * 1.35),
        waveSize: Math.min(12, Math.round(lvl.waveSize * 1.25)),
        speedMultiplier: Number((lvl.speedMultiplier * 1.40).toFixed(2)),
        eggDropRate: Number((lvl.eggDropRate * 1.45).toFixed(4)),
      };
    }
    return lvl;
  });
}

